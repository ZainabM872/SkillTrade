\set ON_ERROR_STOP on
-- Points, learning and moderation. Run after the accounts and scheduling schema.
BEGIN;
SET LOCAL search_path = skilltrade, public;

CREATE TABLE point_transactions (
 transaction_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id bigint REFERENCES sessions(session_id),
 from_user_id bigint REFERENCES users(user_id),
 to_user_id bigint REFERENCES users(user_id),
 amount integer NOT NULL CHECK (amount > 0),
 type varchar(10) NOT NULL CHECK (type IN ('session','grant','reversal')),
 reverses_id bigint UNIQUE REFERENCES point_transactions(transaction_id),
 idempotency_key varchar(120) NOT NULL UNIQUE,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (from_user_id IS DISTINCT FROM to_user_id),
 CHECK ((type='session' AND session_id IS NOT NULL AND from_user_id IS NOT NULL AND to_user_id IS NOT NULL AND reverses_id IS NULL)
     OR (type='grant' AND session_id IS NULL AND from_user_id IS NULL AND to_user_id IS NOT NULL AND reverses_id IS NULL)
     OR (type='reversal' AND reverses_id IS NOT NULL AND from_user_id IS NOT NULL))
);

CREATE UNIQUE INDEX one_payment_per_session ON point_transactions(session_id) WHERE type='session';

CREATE TABLE reviews (
 review_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id bigint NOT NULL REFERENCES sessions(session_id),
 reviewer_id bigint NOT NULL REFERENCES users(user_id),
 reviewee_id bigint NOT NULL REFERENCES users(user_id),
 rating integer NOT NULL CHECK (rating BETWEEN 1 AND 5),
 comment text,
 status varchar(10) NOT NULL DEFAULT 'visible' CHECK (status IN ('visible','hidden')),
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (reviewer_id <> reviewee_id),
 UNIQUE(session_id,reviewer_id)
);

CREATE TABLE learning_goals (
 goal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id bigint NOT NULL REFERENCES users(user_id),
 listing_id bigint REFERENCES skill_listings(listing_id),
 title varchar(160) NOT NULL,
 description text,
 target_date date,
 status varchar(12) NOT NULL DEFAULT 'active' CHECK (status IN ('active','completed','archived')),
 created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE goal_progress (
 progress_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 goal_id bigint NOT NULL REFERENCES learning_goals(goal_id),
 session_id bigint REFERENCES sessions(session_id),
 progress_percent integer NOT NULL CHECK (progress_percent BETWEEN 0 AND 100),
 note text,
 recorded_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE messages (
 message_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 session_id bigint REFERENCES sessions(session_id),
 sender_id bigint NOT NULL REFERENCES users(user_id),
 recipient_id bigint NOT NULL REFERENCES users(user_id),
 body text NOT NULL CHECK (length(trim(body)) > 0),
 sent_at timestamptz NOT NULL DEFAULT now(),
 read_at timestamptz,
 status varchar(10) NOT NULL DEFAULT 'visible' CHECK (status IN ('visible','hidden')),
 CHECK (sender_id <> recipient_id)
);

CREATE TABLE reports (
 report_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reporter_id bigint NOT NULL REFERENCES users(user_id),
 assigned_to bigint REFERENCES users(user_id),
 reported_user_id bigint REFERENCES users(user_id),
 listing_id bigint REFERENCES skill_listings(listing_id),
 review_id bigint REFERENCES reviews(review_id),
 message_id bigint REFERENCES messages(message_id),
 session_id bigint REFERENCES sessions(session_id),
 reason text NOT NULL,
 status varchar(12) NOT NULL DEFAULT 'open' CHECK (status IN ('open','reviewing','resolved','escalated','dismissed')),
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (num_nonnulls(reported_user_id,listing_id,review_id,message_id,session_id)=1)
);

CREATE TABLE moderation_actions (
 action_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 report_id bigint REFERENCES reports(report_id),
 actor_id bigint NOT NULL REFERENCES users(user_id),
 target_user_id bigint REFERENCES users(user_id),
 type varchar(16) NOT NULL CHECK (type IN ('warning','restriction','hide_content','role_change','resolve')),
 reason text NOT NULL,
 details jsonb NOT NULL DEFAULT '{}'::jsonb,
 restriction_end timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 CHECK (type<>'hide_content' OR report_id IS NOT NULL),
 CHECK (type NOT IN ('warning','restriction','role_change') OR target_user_id IS NOT NULL)
);

CREATE TABLE platform_settings (
 setting_key varchar(80) PRIMARY KEY,
 value jsonb NOT NULL,
 updated_by bigint NOT NULL REFERENCES users(user_id),
 updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE FUNCTION sara_is_participant(p_session bigint,p_user bigint) RETURNS boolean
LANGUAGE sql STABLE SET search_path = skilltrade, pg_temp AS $$
 SELECT EXISTS(SELECT 1 FROM sessions WHERE session_id=p_session AND p_user IN (teacher_id,learner_id));
$$;

CREATE FUNCTION validate_review() RETURNS trigger LANGUAGE plpgsql SET search_path = skilltrade, pg_temp AS $$
BEGIN
 IF NOT EXISTS(SELECT 1 FROM sessions WHERE session_id=NEW.session_id AND status='completed')
 OR NOT sara_is_participant(NEW.session_id,NEW.reviewer_id) OR NOT sara_is_participant(NEW.session_id,NEW.reviewee_id)
 THEN RAISE EXCEPTION 'Review requires a completed session and its participants'; END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION validate_goal_progress() RETURNS trigger LANGUAGE plpgsql SET search_path = skilltrade, pg_temp AS $$
DECLARE owner_id bigint;
BEGIN
 SELECT user_id INTO STRICT owner_id FROM learning_goals WHERE goal_id=NEW.goal_id;
 IF NEW.session_id IS NOT NULL AND (NOT sara_is_participant(NEW.session_id,owner_id) OR NOT EXISTS(SELECT 1 FROM sessions WHERE session_id=NEW.session_id AND status='completed'))
 THEN RAISE EXCEPTION 'Goal evidence must be the owner''s completed session'; END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION validate_staff() RETURNS trigger LANGUAGE plpgsql SET search_path = skilltrade, pg_temp AS $$
BEGIN
 IF TG_TABLE_NAME='reports' THEN
  IF NEW.assigned_to IS NOT NULL AND NOT EXISTS(SELECT 1 FROM users WHERE user_id=NEW.assigned_to AND role IN ('moderator','admin')) THEN RAISE EXCEPTION 'Report assignee must be staff'; END IF;
 ELSIF TG_TABLE_NAME='moderation_actions' THEN
  IF NOT EXISTS(SELECT 1 FROM users WHERE user_id=NEW.actor_id AND role IN ('moderator','admin')) THEN RAISE EXCEPTION 'Action actor must be staff'; END IF;
  IF NEW.type='role_change' AND NOT EXISTS(SELECT 1 FROM users WHERE user_id=NEW.actor_id AND role='admin') THEN RAISE EXCEPTION 'Role changes require an admin'; END IF;
 ELSE
  IF NOT EXISTS(SELECT 1 FROM users WHERE user_id=NEW.updated_by AND role='admin') THEN RAISE EXCEPTION 'Platform settings require an admin'; END IF;
 END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION apply_points() RETURNS trigger LANGUAGE plpgsql SET search_path = skilltrade, pg_temp AS $$
DECLARE s sessions; original point_transactions;
BEGIN
 PERFORM user_id FROM users WHERE user_id IN (NEW.from_user_id,NEW.to_user_id) ORDER BY user_id FOR UPDATE;
 IF NEW.type='session' THEN
  SELECT * INTO STRICT s FROM sessions WHERE session_id=NEW.session_id FOR UPDATE;
  IF s.status<>'completed' OR NEW.from_user_id<>s.learner_id OR NEW.to_user_id<>s.teacher_id OR NEW.amount<>s.point_cost
  THEN RAISE EXCEPTION 'Payment must match a completed session, learner, teacher and agreed cost'; END IF;
 ELSIF NEW.type='reversal' THEN
  SELECT * INTO STRICT original FROM point_transactions WHERE transaction_id=NEW.reverses_id;
  IF original.type='reversal' OR NEW.amount<>original.amount
    OR NEW.from_user_id IS DISTINCT FROM original.to_user_id
    OR NEW.to_user_id IS DISTINCT FROM original.from_user_id
    OR NEW.session_id IS DISTINCT FROM original.session_id
  THEN RAISE EXCEPTION 'Reversal must exactly reverse an original transaction'; END IF;
 END IF;
 IF NEW.from_user_id IS NOT NULL THEN
  UPDATE users SET point_balance=point_balance-NEW.amount WHERE user_id=NEW.from_user_id AND point_balance>=NEW.amount;
  IF NOT FOUND THEN RAISE EXCEPTION 'Insufficient points'; END IF;
 END IF;
 IF NEW.to_user_id IS NOT NULL THEN UPDATE users SET point_balance=point_balance+NEW.amount WHERE user_id=NEW.to_user_id; END IF;
 RETURN NEW;
END $$;

CREATE FUNCTION ledger_read_only() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Ledger is append-only; insert a reversal instead'; END $$;

CREATE FUNCTION validate_message_participants() RETURNS trigger LANGUAGE plpgsql SET search_path = skilltrade, pg_temp AS $$
BEGIN
 IF NEW.session_id IS NOT NULL AND (NOT sara_is_participant(NEW.session_id,NEW.sender_id) OR NOT sara_is_participant(NEW.session_id,NEW.recipient_id))
 THEN RAISE EXCEPTION 'Session message must be between participants'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER messages_valid BEFORE INSERT OR UPDATE ON messages FOR EACH ROW EXECUTE FUNCTION validate_message_participants();

CREATE TRIGGER review_valid BEFORE INSERT OR UPDATE ON reviews FOR EACH ROW EXECUTE FUNCTION validate_review();

CREATE TRIGGER progress_valid BEFORE INSERT OR UPDATE ON goal_progress FOR EACH ROW EXECUTE FUNCTION validate_goal_progress();

CREATE TRIGGER reports_staff BEFORE INSERT OR UPDATE ON reports FOR EACH ROW EXECUTE FUNCTION validate_staff();

CREATE TRIGGER actions_staff BEFORE INSERT OR UPDATE ON moderation_actions FOR EACH ROW EXECUTE FUNCTION validate_staff();

CREATE TRIGGER settings_staff BEFORE INSERT OR UPDATE ON platform_settings FOR EACH ROW EXECUTE FUNCTION validate_staff();

CREATE TRIGGER ledger_apply BEFORE INSERT ON point_transactions FOR EACH ROW EXECUTE FUNCTION apply_points();

CREATE TRIGGER ledger_no_edits BEFORE UPDATE OR DELETE ON point_transactions FOR EACH ROW EXECUTE FUNCTION ledger_read_only();

CREATE VIEW point_balance_audit AS
 SELECT u.user_id,u.point_balance,
 coalesce((SELECT sum(CASE WHEN p.to_user_id=u.user_id THEN p.amount ELSE -p.amount END)
 FROM point_transactions p WHERE u.user_id IN (p.from_user_id,p.to_user_id)),0)::bigint AS ledger_balance
 FROM users u;

CREATE VIEW current_goal_progress AS
 SELECT g.goal_id,g.user_id,coalesce(p.progress_percent,0) AS progress_percent
 FROM learning_goals g LEFT JOIN LATERAL (
 SELECT progress_percent FROM goal_progress WHERE goal_id=g.goal_id ORDER BY recorded_at DESC,progress_id DESC LIMIT 1) p ON true;

CREATE VIEW average_user_ratings AS SELECT reviewee_id AS user_id, round(avg(rating),2) AS average_rating FROM reviews WHERE status='visible' GROUP BY reviewee_id;

CREATE INDEX reviews_reviewee ON reviews(reviewee_id);

CREATE INDEX goals_user ON learning_goals(user_id);

CREATE INDEX progress_latest ON goal_progress(goal_id,recorded_at DESC,progress_id DESC);

CREATE INDEX reports_queue ON reports(status,assigned_to);

CREATE INDEX actions_report ON moderation_actions(report_id);

CREATE INDEX messages_recipient ON messages(recipient_id,sent_at);
COMMIT;
