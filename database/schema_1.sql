\set ON_ERROR_STOP on
-- Database: Accounts, Discovery, scheduling and Notifications 
-- Must be run first 
BEGIN;
CREATE SCHEMA skilltrade;
SET LOCAL search_path = skilltrade, public;

-- ---------------------------------------------------------------------------
-- Accounts
-- ---------------------------------------------------------------------------

-- User Table
CREATE TABLE users (
    user_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100)  NOT NULL,
    email VARCHAR(150) NOT NULL CHECK (email LIKE '%_@_%'),
    password_hash TEXT NOT NULL,
    role VARCHAR(10) NOT NULL CHECK (role IN ('student','moderator','admin')),
    bio TEXT,
    account_status VARCHAR(12) NOT NULL DEFAULT 'active' CHECK (account_status IN ('active','restricted','deactivated')),
    point_balance INT NOT NULL DEFAULT 0 CHECK (point_balance >= 0),
    created_at timestamptz NOT NULL DEFAULT now()
);
-- all emails must be unique 'A=a'
CREATE UNIQUE INDEX users_email_unique ON users (lower(email));

-- User Settings Table 
CREATE TABLE user_settings (
    user_id bigint PRIMARY KEY REFERENCES users(user_id) ON DELETE CASCADE,
    profile_visibility varchar(10) NOT NULL DEFAULT 'public' CHECK (profile_visibility IN ('public','private')),
    skill_matching boolean NOT NULL DEFAULT true,
    show_reliability boolean NOT NULL DEFAULT true,
    show_activity boolean NOT NULL DEFAULT false,
    notifications_enabled boolean NOT NULL DEFAULT false,
    reminder_minutes integer NOT NULL DEFAULT 60 CHECK (reminder_minutes >= 0), -- default reminder time is 60
    timezone varchar(64) NOT NULL DEFAULT 'MDT'
);

-- Authentication Token Table 
CREATE TABLE auth_tokens (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token_hash text NOT NULL UNIQUE,             
    purpose varchar(10) NOT NULL CHECK (purpose IN ('reset','refresh')),
    expires_at timestamptz NOT NULL,
    revoked_at timestamptz
);

-- Table for Skill Catagories 
CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(80) NOT NULL UNIQUE,
    active boolean NOT NULL DEFAULT true
);

-- Table for Skill Tags 
CREATE TABLE tags (
    tag_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(50) NOT NULL UNIQUE
);

-- Locations Table
CREATE TABLE locations (
    location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_by BIGINT NOT NULL REFERENCES users(user_id),
    location_name varchar(160) NOT NULL,
    latitude NUMERIC(9,6) CHECK (latitude BETWEEN -90 AND 90), -- values contain 9 digits total with 6 after the point 
    longitude NUMERIC(9,6) CHECK (longitude BETWEEN -180 AND 180), -- check they are within range 
    meeting_instructions text,
    CHECK ((latitude IS NULL) = (longitude IS NULL)) -- both must be null at the same time 
);

-- Table for a Skill Listing

CREATE TABLE skill_listings(
    listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES users(user_id),
    category_id BIGINT NOT NULL REFERENCES categories(category_id),
    title VARCHAR(160) NOT NULL,
    description TEXT,
    experience_level VARCHAR(30),
    difficulty VARCHAR(30),
    session_mode VARCHAR(20) NOT NULL CHECK (session_mode IN ('online','in_person','both')),
    duration_minutes INT NOT NULL CHECK (duration_minutes > 0),
    point_cost INT NOT NULL CHECK (point_cost > 0),
    status varchar(10) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','active','hidden')),
    created_at timestamptz NOT NULL DEFAULT now()

);

-- Listing Tag Table 
CREATE TABLE listing_tags (
    listing_id BIGINT NOT NULL REFERENCES skill_listings(listing_id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags(tag_id) ON DELETE CASCADE,
    PRIMARY KEY (listing_id, tag_id) -- composite primary key between listing-id and tag-id
);
 
-- Listing Locations Table
CREATE TABLE listing_locations (
    listing_id BIGINT NOT NULL REFERENCES skill_listings(listing_id) ON DELETE CASCADE,
    location_id BIGINT NOT NULL REFERENCES locations(location_id) ON DELETE CASCADE,
    PRIMARY KEY (listing_id, location_id) -- composite primary key between listing-id and location-id
);

-- ---------------------------------------------------------------------------
-- Scheduling
-- ---------------------------------------------------------------------------

-- Availability Interval Table 
CREATE TABLE availability_intervals(
    slot_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    start_time timestamptz NOT NULL,
    end_time timestamptz NOT NULL,
    CHECK (end_time > start_time),
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('available','busy')),
    source VARCHAR(10) NOT NULL CHECK (source IN ('manual','calendar'))
);

-- Session Table

CREATE TABLE sessions(
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id BIGINT NOT NULL REFERENCES skill_listings(listing_id),
    teacher_id BIGINT NOT NULL REFERENCES users(user_id),
    learner_id BIGINT NOT NULL REFERENCES users(user_id),
    CHECK (teacher_id <> learner_id),
    start_time timestamptz NOT NULL,
    end_time timestamptz NOT NULL,
    CHECK (end_time > start_time),
    mode VARCHAR(10) NOT NULL CHECK (mode IN ('online','in_person')), 
    location_id BIGINT REFERENCES locations(location_id),
    CHECK (mode <> 'in_person' OR location_id IS NOT NULL),
    meeting_instructions TEXT,
    meeting_link TEXT, 
    CHECK (mode <> 'online' OR status NOT IN ('confirmed','completed') OR meeting_link IS NOT NULL), -- check if the link is availible if the session is online and confirmed
    point_cost INT NOT NULL CHECK (point_cost > 0), 
    status VARCHAR(10) NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','confirmed','completed','cancelled','disputed')),
    icon TEXT, 
    created_at timestamptz NOT NULL DEFAULT now()

);

-- Attendance Table 
CREATE TABLE attendance ( -- both teacher and learner get a row for each session
    session_id BIGINT NOT NULL REFERENCES sessions(session_id),
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    status VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','attended','no_show')),
    arrived_at timestamptz,
    confirmed_by BIGINT REFERENCES users(user_id), -- second party 
    confirmed_at timestamptz,
    PRIMARY KEY (session_id, user_id) -- primary key is the combination of both session id and user id 
);

-- Table when user requests to reschedule a session 

CREATE TABLE session_changes(
    change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES sessions(session_id),
    requested_by BIGINT NOT NULL REFERENCES users(user_id),
    type VARCHAR(10) NOT NULL CHECK (type IN ('cancel','reschedule')),
    proposed_start timestamptz,
    proposed_end timestamptz,
    reason TEXT,
    status VARCHAR(10) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected')),
    resolved_at timestamptz
);

-- Notification Table 

CREATE TABLE notifications(
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id),
    session_id BIGINT REFERENCES sessions(session_id),
    type varchar(40) NOT NULL,
    message text NOT NULL,
    scheduled_at timestamptz NOT NULL,
    sent_at timestamptz,
    read_at timestamptz
);

-- ---------------------------------------------------------------------------
-- Functions 
-- ---------------------------------------------------------------------------
-- Validates a session insert using variety of criteria
    -- Booking info must be consistant to corresponding listing 
    -- No Double bookings for one session (uses needs_check flag when the session needs to be searched for double booking)
    -- Once a session is created, the teacher, learner, listing and cost are frozen and cannot be edited

    CREATE FUNCTION validate_session() RETURNS trigger LANGUAGE plpgsql SET search_path = skilltrade, pg_temp AS $$
    DECLARE l skill_listings%ROWTYPE; needs_check boolean := false;
    BEGIN
    
    -- 1. Load the skill listing the session points at
    SELECT * INTO STRICT l FROM skill_listings WHERE listing_id = NEW.listing_id;

    -- 2. New session  must match with its listing
    IF TG_OP = 'INSERT' THEN
        IF l.status <> 'active' THEN
        RAISE EXCEPTION 'Sessions can only be booked on active listings';
        END IF;

        IF NEW.teacher_id <> l.teacher_id THEN
        RAISE EXCEPTION 'Session teacher must be the listing''s teacher';
        END IF;

        IF NEW.point_cost <> l.point_cost THEN
        RAISE EXCEPTION 'Session point_cost must match the listing cost';
        END IF;

    -- 3. If the session already exists the following fields are frozen 
    ELSIF NEW.teacher_id <> OLD.teacher_id
     OR NEW.learner_id <> OLD.learner_id
     OR NEW.listing_id <> OLD.listing_id
     OR NEW.point_cost <> OLD.point_cost THEN
    RAISE EXCEPTION 'Teacher, learner, listing and cost cannot change after booking';
   END IF;

    -- 4. Length of the session must match the listing length 
    IF NEW.end_time - NEW.start_time <> l.duration_minutes * interval '1 minute' THEN
      RAISE EXCEPTION 'Session length must match the listing duration';
    END IF;

    -- 5. Mode must be one the listing offers (insert and update)
    IF (NEW.mode = 'online'    AND l.session_mode = 'in_person')
    OR (NEW.mode = 'in_person' AND l.session_mode = 'online') THEN
        RAISE EXCEPTION 'Session mode is not offered by this listing';
    END IF;

    -- 6. Decide if the double booking check is needed
    IF NEW.status = 'confirmed' THEN
        IF TG_OP = 'INSERT' THEN
            needs_check := true;
        ELSIF OLD.status <> 'confirmed'
            OR OLD.start_time <> NEW.start_time
            OR OLD.end_time <> NEW.end_time THEN
            needs_check := true;
        END IF;
    END IF;

    -- 7. Both people must be free before a session becomes confirmed
    -- Double booking check 
    IF needs_check THEN
        -- Lock both users into the session 
        PERFORM user_id
        FROM users
        WHERE user_id IN (NEW.teacher_id, NEW.learner_id)
        ORDER BY user_id
        FOR UPDATE;
    
        IF EXISTS (
        SELECT 1
        FROM sessions s
        WHERE s.session_id IS DISTINCT FROM NEW.session_id
            AND s.status = 'confirmed'
            AND (s.teacher_id IN (NEW.teacher_id, NEW.learner_id)
            OR s.learner_id IN (NEW.teacher_id, NEW.learner_id))
            AND tstzrange(s.start_time, s.end_time) && tstzrange(NEW.start_time, NEW.end_time)
        ) THEN
        RAISE EXCEPTION 'A participant already has a confirmed session at that time';
        END IF;
    END IF;
    RETURN NEW;
END $$;


-- Make sure the person named on an attendance row or a session change request is actually the teacher or the learner of that session.

CREATE FUNCTION validate_session_participants() RETURNS trigger LANGUAGE plpgsql SET search_path = skilltrade, pg_temp AS $$
DECLARE person BIGINT;   -- the person this row is about
BEGIN
  -- 1. Work out the person  
  IF TG_TABLE_NAME = 'attendance' THEN -- attendence 
    person := NEW.user_id;
  ELSE                                  -- session_changes
    person := NEW.requested_by;
  END IF;

  -- 2. This person must be the teacher or the learner of the session
  IF NOT EXISTS (
    SELECT 1
    FROM sessions
    WHERE session_id = NEW.session_id
      AND person IN (teacher_id, learner_id)
  ) THEN
    RAISE EXCEPTION 'User must be a participant of the session';
  END IF;

  -- 3. save the row
  RETURN NEW;
END $$;

-- The following are triggers for the functions above, they are run when the corresponding table is added or changed 

CREATE TRIGGER sessions_valid BEFORE INSERT OR UPDATE ON sessions
FOR EACH ROW EXECUTE FUNCTION validate_session();

CREATE TRIGGER attendance_valid BEFORE INSERT OR UPDATE ON attendance
FOR EACH ROW EXECUTE FUNCTION validate_session_participants();

CREATE TRIGGER changes_valid BEFORE INSERT OR UPDATE ON session_changes
FOR EACH ROW EXECUTE FUNCTION validate_session_participants();

-- ---------------------------------------------------------------------------
-- View for Reability Scores 
-- ---------------------------------------------------------------------------
-- This view updates as the tables are updated, which tracks how many sessions a user attended and missed.
-- It calculates their average reliability score 

CREATE VIEW user_reliability AS
SELECT
  u.user_id,
  COUNT(*) FILTER (WHERE a.status = 'attended') AS attended,
  COUNT(*) FILTER (WHERE a.status = 'no_show')  AS no_shows,
  round(
    COUNT(*) FILTER (WHERE a.status = 'attended')::numeric
    / NULLIF(COUNT(*) FILTER (WHERE a.status IN ('attended','no_show')), 0),2) AS reliability
FROM users u
LEFT JOIN attendance a ON a.user_id = u.user_id -- take user tables and the attendence info 
GROUP BY u.user_id;

